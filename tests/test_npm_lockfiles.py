def test_semver_precedence_follows_the_spec() -> None:
    # SemVer 2.0 §11's example, shuffled.
    spec = [
        "1.0.0-alpha",
        "1.0.0-alpha.1",
        "1.0.0-alpha.beta",
        "1.0.0-beta",
        "1.0.0-beta.2",
        "1.0.0-beta.11",
        "1.0.0-rc.1",
        "1.0.0",
        "1.9.0",
        "1.10.0",
        "2.0.0",
    ]
    assert sorted(reversed(spec), key=semver_key) == spec
    assert semver_key("1.0.0+build.1") == semver_key("1.0.0+other") == semver_key("1.0.0")
    for bad in ("latest", "1.0", "01.0.0", "1.0.0-01", "v1.0.0", "1.0.0\n", "9" * 300 + ".0.0"):
        assert semver_key(bad)[0] == 0 and semver_key(bad) < semver_key("0.0.0-0")


def test_npm_baselines_use_semver_and_pypi_baselines_use_pep_440() -> None:
    base = [
        Pin("lib", "2.0.0-alpha.beta", 1, ecosystem="npm"),
        Pin("lib", "1.0.0", 2, ecosystem="npm"),
    ]
    (change,) = diff_pins(base, [Pin("lib", "2.0.0", 1, ecosystem="npm")])
    assert (change.baseline, change.ecosystem) == ("2.0.0-alpha.beta", "npm")
    # "2.0.0-alpha.beta" isn't PEP 440, so on PyPI it sorts below every version.
    pypi = [Pin("lib", "2.0.0-alpha.beta", 1), Pin("lib", "1.0.0", 2)]
    (change,) = diff_pins(pypi, [Pin("lib", "2.0.0", 1)])
    assert (change.baseline, change.ecosystem) == ("1.0.0", "pypi")
    assert version_key("pypi", "1.0.post1")[0] == 1 and version_key("npm", "1.0.post1")[0] == 0


def test_build_metadata_ties_pick_a_stable_baseline() -> None:
    base = [Pin("lib", v, 1, ecosystem="npm") for v in ("1.0.0+b", "1.0.0+a", "1.0.0+c")]
    for _ in range(3):
        (change,) = diff_pins(base, [Pin("lib", "1.0.0+d", 1, ecosystem="npm")])
        assert change.baseline == "1.0.0+c"


def test_the_same_name_in_two_ecosystems_is_two_packages() -> None:
    base = [Pin("ms", "2.1.3", 1)]
    head = [Pin("ms", "2.1.3", 1, ecosystem="npm")]
    (change,) = diff_pins(base, head)
    assert (change.ecosystem, change.baseline) == ("npm", None)
    unchecked = [Pin("ms", None, 1, "unsupported", "git source")]
    assert new_unchecked(unchecked, [Pin("ms", None, 1, "unsupported", "git source", "npm")])
    pypi = Change("pypi", "ms", None, "2.1.3", lockfile="uv.lock", line=1)
    npm = Change("npm", "ms", None, "2.1.3", lockfile="package-lock.json", line=1)
    assert dedupe([pypi, npm, pypi]) == [pypi, npm]


