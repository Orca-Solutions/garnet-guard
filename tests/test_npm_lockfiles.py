def test_package_lock_v3_pins_every_installed_package_at_its_key_line() -> None:
    pins = parse("package-lock.json", fixture("package-lock-base.json"))
    assert rows(pins) == BASE_PINS
    assert {p.ecosystem for p in pins} == {"npm"}
    text = fixture("package-lock-base.json").decode().splitlines()
    assert text[57 - 1].strip() == '"node_modules/my-ms": {'
    assert text[35 - 1].strip() == '"node_modules/debug/node_modules/ms": {'


