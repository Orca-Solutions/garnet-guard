def _git(repo: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=repo, check=True, capture_output=True)


def test_check_reads_npm_lockfiles_from_git(tmp_path, monkeypatch, capsys) -> None:
    from garnet_guard import cli

    _git(tmp_path, "init", "-q")
    _git(tmp_path, "config", "user.email", "t@example.com")
    _git(tmp_path, "config", "user.name", "t")
    _git(tmp_path, "config", "commit.gpgsign", "false")
    (tmp_path / "package-lock.json").write_bytes(fixture("package-lock-base.json"))
    (tmp_path / "yarn.lock").write_bytes(fixture("yarn-base.lock"))
    _git(tmp_path, "add", ".")
    _git(tmp_path, "commit", "-qm", "base")
    (tmp_path / "package-lock.json").write_bytes(fixture("package-lock-head.json"))
    (tmp_path / "yarn.lock").write_bytes(fixture("yarn-head.lock"))
    seen: list[Change] = []

    def fake_evaluate(changes, *, policy=None, options=None):
        seen.extend(changes)
        return [
            run_checks(c, release(c.baseline or "0"), release(c.candidate, tag=False))
            for c in changes
        ]

    monkeypatch.setattr(cli, "evaluate", fake_evaluate)
    monkeypatch.chdir(tmp_path)
    assert main(["check", "--git-base", "HEAD", "--format", "json", "--no-policy"]) == 0
    doc = json.loads(capsys.readouterr().out)
    # ms 2.1.2 → 2.1.3 is in both lockfiles and checked once, from the first.
    assert [
        (c.ecosystem, c.package, c.baseline, c.candidate, c.lockfile, c.line) for c in seen
    ] == [
        ("npm", "ms", "2.1.2", "2.1.3", "package-lock.json", 51),
        ("npm", "debug", "2.6.9", "4.3.7", "yarn.lock", 11),
    ]
    assert {c["ecosystem"] for c in doc["changes"]} == {"npm"}
    log = sarif.render(doc)
    regions = {
        r["locations"][0]["physicalLocation"]["artifactLocation"]["uri"]: r["locations"][0][
            "physicalLocation"
        ]["region"]["startLine"]
        for r in log["runs"][0]["results"]
    }
    assert regions == {"package-lock.json": 51, "yarn.lock": 11}
    comment = markdown.render(doc)
    assert "`ms` `2.1.2` → `2.1.3`" in comment and "pypi.org" not in comment
