FIXTURES = Path(__file__).parent / "fixtures" / "npm"
REG = "https://registry.npmjs.org"


def fixture(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


def rows(pins: list[Pin]) -> list[tuple[str, str | None, int, str, str | None]]:
    return [(p.package, p.version, p.line, p.source, p.detail) for p in pins]


def lock(packages: dict[str, object], version: int = 3) -> bytes:
    """A package-lock.json with a root entry and these packages."""
    doc = {
        "name": "app",
        "version": "1.0.0",
        "lockfileVersion": version,
        "requires": True,
        "packages": {"": {"name": "app", "version": "1.0.0"}, **packages},
    }
    return json.dumps(doc, indent=2).encode()


def reg(pkg: str, version: str, /, **extra: object) -> dict[str, object]:
    """A registry entry as npm writes it."""
    base = pkg.rpartition("/")[2]
    return {
        "version": version,
        "resolved": f"{REG}/{pkg}/-/{base}-{version}.tgz",
        "integrity": "sha512-AAAA",
        **extra,
    }


YARN_HEADER = (
    "# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n"
)


def yarn(body: str) -> bytes:
    return (YARN_HEADER + body).encode()


