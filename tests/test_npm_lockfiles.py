# --- hostile package-lock.json -----------------------------------------------------------


@pytest.mark.parametrize(
    ("data", "message"),
    [
        (b"[" * 100_000 + b"]" * 100_000, "nested too deeply"),
        (b'{"lockfileVersion": 3, "packages": {"hunter2": }}', "invalid JSON at line 1"),
        (b"[1, 2]", "isn't a JSON object"),
        (b'{"lockfileVersion": 1' + b"0" * 5000 + b"}", "invalid JSON"),
        (b'{"packages": {}}', "no lockfileVersion"),
        (b'{"lockfileVersion": "hunter2", "packages": {}}', "no lockfileVersion"),
        (b'{"lockfileVersion": true, "packages": {}}', "no lockfileVersion"),
        (b'{"lockfileVersion": 4, "packages": {}}', "lockfileVersion 4 isn't one Garnet reads"),
        (b'{"lockfileVersion": 3, "packages": ["hunter2"]}', "needs a packages object"),
        (b'{"lockfileVersion": 3}', "needs a packages object"),
        (b'{"lockfileVersion": 1, "dependencies": ["hunter2"]}', "isn't an object"),
        (lock({"node_modules/x": "hunter2"}), "entry at line 11 isn't an object"),
        (lock({"node_modules/../x": reg("x", "1.0.0")}), "isn't a plain relative path"),
        (lock({"node_modules/./x": reg("x", "1.0.0")}), "isn't a plain relative path"),
        (lock({"/node_modules/x": reg("x", "1.0.0")}), "isn't a plain relative path"),
        (lock({"node_modules\\x": reg("x", "1.0.0")}), "isn't a plain relative path"),
        (lock({"node_modules/x": {"version": ["hunter2"]}}), "version that isn't a string"),
        (lock({"node_modules/x": {"version": "1.0.0", "link": "hunter2"}}), "link that isn't true"),
        (
            lock({"node_modules/x": {**reg("x", "1.0.0"), "inBundle": 1}}),
            "inBundle that isn't true",
        ),
        (b"\xff\xfe{}", "not UTF-8"),
    ],
)
def test_hostile_package_locks_are_lockfile_errors(data: bytes, message: str) -> None:
    with pytest.raises(LockfileError) as err:
        parse("package-lock.json", data)
    assert message in str(err.value)
    assert "hunter2" not in str(err.value)
    assert str(err.value).startswith("package-lock.json")


