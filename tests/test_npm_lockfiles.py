def test_package_lock_v1_tree_gives_the_same_packages() -> None:
    pins = parse("package-lock.json", fixture("package-lock-v1.json"))
    assert sorted((p.package, p.version) for p in pins) == sorted((r[0], r[1]) for r in BASE_PINS)
    by_version = {(p.package, p.version): p.line for p in pins}
    text = fixture("package-lock-v1.json").decode().splitlines()
    assert text[by_version[("ms", "2.0.0")] - 1].strip() == '"ms": {'  # nested under debug
    assert text[by_version[("ms", "2.1.1")] - 1].strip() == '"my-ms": {'  # the alias


